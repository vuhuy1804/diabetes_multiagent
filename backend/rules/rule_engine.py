def rule_catalog() -> list[dict[str, Any]]:
    """Stable, source-linked definitions without patient or prediction values."""
    return [{
        'rule_id': r.rule_id, 'title': r.title, 'criterion': r.criterion,
        'severity': r.severity, 'category': r.category,
        'required_fields': list(r.required_fields), 'source': dict(r.source),
    } for r in RULES]


def _validated_prediction(raw: Any) -> dict[str, Any]:
    """Accept exactly the core keys emitted by Phase 1 DL Prediction Agent.

    We allow additive metadata keys, but never infer an absent prediction or
    silently parse strings/bools. API caller supplied data is *not* authenticated.
    """
    if not isinstance(raw, dict):
        raise RuleInputError('prediction must be the structured DL Agent payload')
    if type(raw.get('prediction')) is not int or raw['prediction'] not in (0, 1):
        raise RuleInputError('prediction.prediction must be integer 0 or 1')
    score = raw.get('model_score_class_1')
    if isinstance(score, bool) or not isinstance(score, (int, float)):
        raise RuleInputError('prediction.model_score_class_1 must be numeric')
    try:
        score = float(score)
    except (ValueError, OverflowError):
        raise RuleInputError('prediction.model_score_class_1 must be finite') from None
    if not math.isfinite(score) or not 0.0 <= score <= 1.0:
        raise RuleInputError('prediction.model_score_class_1 must be within [0,1]')
    if type(raw.get('score_is_calibrated')) is not bool:
        raise RuleInputError('prediction.score_is_calibrated must be boolean')
    if raw.get('output_kind') != 'dataset_label_classification':
        raise RuleInputError('prediction.output_kind is unsupported')
    version = raw.get('model_version')
    if not isinstance(version, str) or not version.strip() or len(version) > 128:
        raise RuleInputError('prediction.model_version is required')
    if raw.get('input_feature_names') != list(FEATURE_NAMES):
        raise RuleInputError('prediction.input_feature_names must match the model feature schema')
    return {
        'prediction': raw['prediction'],
        'model_score_class_1': score,
        'score_is_calibrated': raw['score_is_calibrated'],
        'model_version': version,
    }


def evaluate_rules(features: Any, prediction_payload: Any) -> dict[str, Any]:
    """Evaluate all rules in deterministic order, return only grounded flags.

    Data Agent normalizes the features earlier; here strict schema checks prevent
    bypassing that contract. No patient inputs are persisted or logged.
    """
    try:
        clean = validate_features(features)
    except FeatureValidationError as exc:
        raise RuleInputError('features are not canonical; run Patient Data Agent first') from exc
    pred = _validated_prediction(prediction_payload)

    flags: list[dict[str, Any]] = []
    evaluations: list[dict[str, Any]] = []
    evidence: list[dict[str, Any]] = []
    for rule in RULES:
        triggered = bool(rule.match(clean, pred))
        evaluations.append({'rule_id': rule.rule_id, 'triggered': triggered})
        if not triggered:
            continue
        flags.append({
            'rule_id': rule.rule_id,
            'title': rule.title,
            'category': rule.category,
            'severity': rule.severity,
            'criterion': rule.criterion,
            'message': rule.message,
            'requires_human_review': rule.severity == 'review',
            'source': dict(rule.source),
        })
        evidence.append({
            'kind': 'rule_reference', 'rule_id': rule.rule_id,
            'criterion': rule.criterion, 'source': dict(rule.source),
        })

    return {
        'rule_set_version': RULE_SET_VERSION,
        'evaluation_kind': 'educational_flags_not_diagnosis',
        'model_version': pred['model_version'],
        'rules_evaluated': len(RULES),
        'triggered_rules_count': len(flags),
        'review_required': any(flag['requires_human_review'] for flag in flags),
        'flags': flags,
        'evaluations': evaluations,
        'evidence': evidence,
        'limitations': [
            'Rules do not diagnose diabetes or identify its type.',
            'HbA1c and glucose are interpreted only as reference examples; units, test method and clinical context must be verified.',
            'The prediction payload is caller-supplied; it must come from a trusted DL Agent in the future Coordinator workflow.',
            'Rules must be clinically reviewed before any real-world use.',
        ],
    }
